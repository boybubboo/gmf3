export function resolvePlatformerMovement(level?: Partial<GameLevel> | null): PlatformerMovementConfig {
  const raw = level?.platformerTuning ?? level?.sideScrollerConfig?.movementTuning;
  return {
    ...DEFAULT_PLATFORMER_MOVEMENT,
    ...(raw ?? {}),
  };
}

export function createPlatformerModuleEntity(
  moduleId: PlatformerModuleId,
  pos: BoardPoint,
  opts?: {
    elevationY?: number;
    configPatch?: Partial<PlatformerAddonConfig>;
    name?: string;
    rotation?: number;
  }
): LevelEntity {
  const spec = PLATFORMER_MODULE_MAP[moduleId] ?? PLATFORMER_MODULES[0];
  const cfg: PlatformerAddonConfig = {
    ...JSON.parse(JSON.stringify(spec.defaultConfig)),
    ...(opts?.configPatch ?? {}),
  };
  return createEntity(spec.entityKind, opts?.name ?? spec.label, pos.x, pos.y, {
    scale: spec.defaultScale ?? 1,
    rotation: opts?.rotation ?? 0,
    elevationY: opts?.elevationY,
    health: spec.defaultHealth ?? 2,
    speed: spec.defaultSpeed ?? 3.4,
    damage: spec.defaultDamage ?? 1,
    brain:
      moduleId === 'enemyFlyer'
        ? 'Flyer'
        : moduleId === 'enemyPatroller' || moduleId === 'enemyCharger' || moduleId === 'enemySpiked'
        ? 'Patroller'
        : 'Guardian',
    styleTint: cfg.colorTag ?? spec.accent,
    platformRunning: true,
    platformSpeed: cfg.speed ?? 3,
    platformWait: cfg.pauseSec ?? 0.5,
    platformerAddon: cfg,
  });
}
